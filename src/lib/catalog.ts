export function searchSample(query: string, mode: TransportMode) {
  const q = query.trim().toLowerCase()
  return SAMPLE_PLACES.filter((place) => place.mode === mode).filter((place) => {
    if (!q) return true
    return (
      place.name.toLowerCase().includes(q) ||
      place.city.toLowerCase().includes(q) ||
      place.detail.toLowerCase().includes(q)
    )
  })
}

export function toPlace(place: (typeof SAMPLE_PLACES)[number]): Place {
  return {
    id: place.id,
    name: place.name,
    detail: place.detail,
    lat: place.lat,
    lng: place.lng,
    kind: place.kind,
    source: 'sample',
  }
}
